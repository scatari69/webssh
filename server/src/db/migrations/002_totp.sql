-- 002_totp — защита от повторного использования кода и быстрый поиск
-- кодов восстановления.

-- Номер временного шага последнего принятого кода. Код действителен ~90
-- секунд (шаг 30 с плюс допуск на дрейф в обе стороны), и без этой отметки
-- подсмотренный код можно предъявить второй раз, пока окно не закрылось.
-- Принимается только шаг строго больше сохранённого.
ALTER TABLE users ADD COLUMN totp_last_step INTEGER;

-- Код восстановления ищется точным совпадением хеша, а не перебором строк
-- пользователя.
CREATE INDEX idx_recovery_codes_lookup ON recovery_codes (user_id, code_hash);
